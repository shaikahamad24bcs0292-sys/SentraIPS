"""
IPsec Configuration Generator for strongSwan testbed.
Supports Phase 1 specifications:
- VPN mode: Tunnel
- IP version: IPv4
- Encryption: AES-128-CBC, AES-256-GCM
- PFS: Enabled, Disabled
- DH Groups: 14 (modp2048), 19 (ecp256), etc.
"""

from dataclasses import dataclass, asdict
import json
from typing import Dict, Any, Optional


DH_GROUP_MAP = {
    14: "modp2048",
    19: "ecp256",
    5: "modp1536",
    20: "ecp384",
}


@dataclass
class IPsecConfig:
    vpn_mode: str = "tunnel"
    ip_version: str = "ipv4"
    encryption: str = "AES-256-GCM"  # "AES-128-CBC" or "AES-256-GCM"
    pfs: bool = True
    dh_group: int = 19  # 14 or 19
    traffic_type: str = "web"  # "icmp", "web", "video", "voip"
    capture_id: str = "demo_001"
    left_ip: str = "172.28.0.10"
    right_ip: str = "172.28.0.20"
    left_subnet: str = "10.10.1.0/24"
    right_subnet: str = "10.10.2.0/24"
    psk: str = "SentraIPS_SIH2026_Key!"

    @property
    def dh_name(self) -> str:
        return DH_GROUP_MAP.get(self.dh_group, "ecp256")

    def get_ike_proposal(self) -> str:
        """Returns strongSwan IKE proposal string."""
        dh = self.dh_name
        if "GCM" in self.encryption.upper():
            return f"aes256gcm16-sha256-{dh},aes256-sha256-{dh}"
        else:
            return f"aes128-sha256-{dh}"

    def get_esp_proposal(self) -> str:
        """Returns strongSwan ESP proposal string with or without PFS."""
        dh = self.dh_name
        if "GCM" in self.encryption.upper():
            if self.pfs:
                return f"aes256gcm16-{dh}!"
            else:
                return "aes256gcm16!"
        else:
            if self.pfs:
                return f"aes128-sha256-{dh}!"
            else:
                return "aes128-sha256!"

    def generate_ipsec_conf(self, role: str = "left") -> str:
        """
        Generate ipsec.conf content for strongSwan.
        role: "left" (initiator, Gateway A) or "right" (responder, Gateway B)
        """
        ike_prop = self.get_ike_proposal()
        esp_prop = self.get_esp_proposal()
        auto_action = "start" if role == "left" else "add"

        conf = f"""# strongSwan IPsec configuration generated by SentraIPS
# Capture ID: {self.capture_id}
# Encryption: {self.encryption} | PFS: {self.pfs} | DH: {self.dh_group} ({self.dh_name})

config setup
    charondebug="ike 2, knl 2, cfg 2, esp 2"
    uniqueids=yes

conn %default
    keyexchange=ikev2
    ikelifetime=60m
    keylife=20m
    rekeymargin=3m
    keyingtries=3
    authby=secret
    mobike=no

conn ipsec-tunnel
    left={self.left_ip}
    leftsubnet={self.left_subnet}
    leftid=@moon.ipsec.local
    right={self.right_ip}
    rightsubnet={self.right_subnet}
    rightid=@sun.ipsec.local
    type={self.vpn_mode}
    ike={ike_prop}
    esp={esp_prop}
    auto={auto_action}
"""
        return conf

    def generate_ipsec_secrets(self) -> str:
        """Generate ipsec.secrets content."""
        return f"""# strongSwan IPsec secrets generated by SentraIPS
@moon.ipsec.local @sun.ipsec.local : PSK "{self.psk}"
"""

    def generate_metadata(self, extra_fields: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Generate ground-truth metadata matching exact project specification."""
        meta = {
            "capture_id": self.capture_id,
            "vpn_mode": self.vpn_mode,
            "ip_version": self.ip_version,
            "encryption": self.encryption,
            "pfs": self.pfs,
            "dh_group": self.dh_group,
            "dh_group_name": self.dh_name,
            "traffic_type": self.traffic_type,
            "ike_proposal": self.get_ike_proposal(),
            "esp_proposal": self.get_esp_proposal(),
        }
        if extra_fields:
            meta.update(extra_fields)
        return meta
